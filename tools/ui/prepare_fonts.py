#!/usr/bin/env python3
"""Fetch the pinned Material Symbols font, verify it and regenerate icon assets.

Development tool only; the application never downloads fonts. Outputs:
  ui/theme/fonts/MaterialSymbolsRounded.ttf  subset of the glyphs in symbols.txt
  ui/theme/Symbols.qml                       name -> codepoint singleton
Requires fontTools (pyftsubset).
"""

import hashlib
import re
import shutil
import sys
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "build" / "ui-assets"
FONTS = ROOT / "ui" / "theme" / "fonts"
SYMBOLS_QML = ROOT / "ui" / "theme" / "Symbols.qml"

MATERIAL_ICONS = "https://raw.githubusercontent.com/google/material-design-icons/737e3324305806514d7909874fa1818ae1808232/"

PINNED = {
    "MaterialSymbolsRounded.ttf": (
        MATERIAL_ICONS + "variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.ttf",
        "95b24392bb49efd1bc3e92cff4e2452ad094461bab7c97e7d8723fab97e330ca",
    ),
    "MaterialSymbolsRounded.codepoints": (
        MATERIAL_ICONS + "variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints",
        "225bd09137103cb7746bc93dc08d08764c9f0c3bd04f4b958d4a3c3c19432dd6",
    ),
    "MaterialSymbols-LICENSE": (
        MATERIAL_ICONS + "LICENSE",
        "58d1e17ffe5109a7ae296caafcadfdbe6a7d176f0bc4ab01e12a689b0499d8bd",
    ),
}

IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]*$")
# ECMAScript/QML words that cannot be property names; such icons get a trailing "_".
RESERVED = {
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete",
    "do", "else", "enum", "export", "extends", "false", "finally", "for", "function", "if",
    "import", "in", "instanceof", "new", "null", "return", "super", "switch", "this", "throw",
    "true", "try", "typeof", "var", "void", "while", "with", "yield", "let", "static",
    "implements", "interface", "package", "private", "protected", "public", "await",
    "property", "signal", "readonly", "alias", "names",
}


def property_name(icon: str) -> str:
    return icon + "_" if icon in RESERVED else icon


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fetch(name: str) -> Path:
    url, expected = PINNED[name]
    target = CACHE / name
    if not target.exists() or sha256(target) != expected:
        CACHE.mkdir(parents=True, exist_ok=True)
        print(f"download {name}")
        with urllib.request.urlopen(url, timeout=120) as response:
            target.write_bytes(response.read())
    actual = sha256(target)
    if actual != expected:
        sys.exit(f"{name}: SHA-256 mismatch ({actual}), refusing to continue")
    return target


def read_icon_names() -> list[str]:
    names = []
    for line in (FONTS / "symbols.txt").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if not IDENTIFIER.match(line):
            sys.exit(f"symbols.txt: '{line}' is not a valid QML property name")
        if line in names:
            sys.exit(f"symbols.txt: duplicate '{line}'")
        names.append(line)
    return names


def read_codepoints(path: Path) -> dict[str, int]:
    table = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        name, value = line.split()
        table[name] = int(value, 16)
    return table


def subset_symbols(source: Path, codepoints: list[int], target: Path) -> None:
    options = subset.Options()
    options.layout_features = []  # glyphs are addressed by codepoint, not ligature
    options.notdef_outline = True
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    font = TTFont(source, recalcTimestamp=False)  # reproducible output
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.save(target)


def write_symbols_qml(names: list[str], table: dict[str, int]) -> None:
    lines = [
        "// Generated by tools/ui/prepare_fonts.py from fonts/symbols.txt. Do not edit.",
        "// Icons whose name is a reserved word get a trailing underscore (delete -> delete_).",
        "pragma Singleton",
        "import QtQml",
        "",
        "QtObject {",
    ]
    props = [property_name(n) for n in names]
    lines += [f'    readonly property string {p}: "\\u{table[n]:04x}"' for p, n in zip(props, names)]
    lines += ["", "    // Every property above, in symbols.txt order (for galleries and lookups)."]
    lines += ["    readonly property list<string> names: ["]
    lines += [f'        "{p}",' for p in props[:-1]] + [f'        "{props[-1]}"']
    lines += ["    ]", "}", ""]
    SYMBOLS_QML.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    for name in PINNED:
        fetch(name)

    shutil.copyfile(CACHE / "MaterialSymbols-LICENSE", FONTS / "MaterialSymbols-LICENSE")

    names = read_icon_names()
    table = read_codepoints(CACHE / "MaterialSymbolsRounded.codepoints")
    missing = [n for n in names if n not in table]
    if missing:
        sys.exit(f"unknown icon names: {', '.join(missing)}")
    if any(table[n] > 0xFFFF for n in names):
        sys.exit("codepoints above U+FFFF need a different escape in Symbols.qml")

    target = FONTS / "MaterialSymbolsRounded.ttf"
    subset_symbols(CACHE / "MaterialSymbolsRounded.ttf", sorted({table[n] for n in names}), target)
    write_symbols_qml(names, table)

    for path in sorted(FONTS.glob("*.ttf")):
        print(f"{path.relative_to(ROOT)}  {path.stat().st_size} bytes  sha256={sha256(path)}")
    print(f"{len(names)} icons -> {SYMBOLS_QML.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
